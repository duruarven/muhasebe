const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { Store } = require("../src/store");
const { createMobileServer } = require("../src/mobile-server");
const D = require("../src/domain");
test("Mobil oturum, erişim sınırı ve masaüstüyle ortak tahsilat verisi", async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "muhasebe-mobile-"));
  const store = new Store(path.join(dir, "data.json"));
  const service = createMobileServer(store, { host: "127.0.0.1" });
  const port = await service.listen(), base = `http://127.0.0.1:${port}`;
  t.after(async () => { await service.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  const post = (op, input, cookie = "", origin = base) => fetch(`${base}/api/${op}`, { method: "POST", headers: { "Content-Type": "application/json", origin, cookie }, body: JSON.stringify(input) });
  assert.match(await (await fetch(base)).text(), /Mobil giriş/);
  assert.equal((await fetch(base + "/api/read")).status, 401);
  assert.equal((await fetch(base + "/api/backup")).status, 401);
  assert.equal((await fetch(base + "/store.js")).status, 404);
  assert.equal((await post("login", { code: service.code }, "", "http://foreign.example")).status, 403);
  assert.equal((await post("login", { code: "wrong" })).status, 401);
  const login = await post("login", { code: service.code });
  const cookie = login.headers.get("set-cookie").split(";")[0];
  assert.match(login.headers.get("set-cookie"), /HttpOnly; SameSite=Strict/);
  let result = await post("add", { kind: "contacts", input: { name: "Mobil cari", type: "customer", openingAmount: "1000", openingSide: "receivable", openingDate: "2026-10-17" } }, cookie);
  assert.equal((await result.json()).ok, true);
  const c = store.data.contacts[0];
  store.add("accounts", { name: "Masaüstü kasa", type: "cash" });
  result = await post("add", { kind: "transactions", input: { contactId: c.id, accountId: store.data.accounts[0].id, type: "income", amount: "300,01", description: "Mobil tahsilat", date: "2026-10-17" } }, cookie);
  assert.equal((await result.json()).ok, true);
  assert.equal(D.balance(store.data, c.id), 69999);
  assert.equal(D.balance(new Store(store.file).data, c.id), 69999);
  const read = await (await fetch(base + "/api/read", { headers: { cookie } })).json();
  assert.equal(D.balance(read.data, c.id), 69999);
  assert.match(await (await fetch(base, { headers: { cookie } })).text(), /web-bridge.js/);
  const backup = await (await fetch(base + "/api/backup", { headers: { cookie } })).json();
  assert.equal(D.balance(backup, c.id), 69999);
  const csv = await (await fetch(base + "/api/ledger?contactId=" + c.id, { headers: { cookie } })).text();
  assert.match(csv, /Mobil tahsilat/);
  assert.equal((await post("add", { kind: "transactions", input: { type: "income", amount: "-1" } }, cookie)).status, 400);
  assert.equal(store.data.transactions.length, 1);
  assert.equal((await post("remove", { kind: "accounts", id: store.data.accounts[0].id }, cookie, "http://foreign.example")).status, 403);
  assert.equal((await post("logout", {}, cookie)).status, 200);
  assert.equal((await fetch(base + "/api/read", { headers: { cookie } })).status, 401);
});
