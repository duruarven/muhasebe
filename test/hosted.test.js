const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs"), os = require("node:os"), path = require("node:path");
const { hostedOptions } = require("../src/hosted-auth");
const { start } = require("../src/web-server");
const { importBackup } = require("../src/backup-import");
const { Store } = require("../src/store");
const D = require("../src/domain");
function fixture(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "isletmem-hosted-"));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  return { dir, env: { APP_ORIGIN: "https://muhasebe.example", APP_PASSWORD: "synthetic-long-password", DATA_DIR: dir, PORT: "0" } };
}
test("İnternet yapılandırması HTTPS, kalıcı veri dizini ve güçlü şifre ister", async t => {
  const { env } = fixture(t);
  for (const patch of [{ APP_ORIGIN: "http://example.com" }, { APP_ORIGIN: "https://example.com/path" }, { APP_ORIGIN: "https://user:pass@example.com" }, { APP_PASSWORD: "short" }, { DATA_DIR: "relative" }]) assert.throws(() => hostedOptions({ ...env, ...patch }));
  const opts = hostedOptions(env);
  assert.equal(await opts.authenticate(env.APP_PASSWORD), true);
  assert.equal(await opts.authenticate("incorrect"), false);
  assert.equal(await opts.authenticate(null), false);
  assert.equal(hostedOptions({ ...env, APP_ORIGIN: undefined, RENDER_EXTERNAL_URL: env.APP_ORIGIN }).origin, env.APP_ORIGIN);
});
test("İnternet oturumu HTTPS kaynağına bağlı; iki cihaz aynı kalıcı bakiyeyi görür", async t => {
  const { env } = fixture(t);
  let instance = await start(env);
  t.after(() => instance.shutdown());
  let base = `http://127.0.0.1:${instance.service.server.address().port}`;
  const post = (op, input, cookie = "", origin = env.APP_ORIGIN) => fetch(base + "/api/" + op, { method: "POST", headers: { "Content-Type": "application/json", Origin: origin, cookie }, body: JSON.stringify(input) });
  assert.equal((await fetch(base + "/healthz")).status, 200);
  assert.equal((await fetch(base + "/api/read")).status, 401);
  const page = await (await fetch(base)).text();
  assert.match(page, /Giriş şifresi/);
  assert.doesNotMatch(page, /aynı Wi-Fi|synthetic-long-password/);
  assert.equal((await post("login", { code: env.APP_PASSWORD }, "", "https://attacker.example")).status, 403);
  const login = await post("login", { code: env.APP_PASSWORD });
  assert.equal(login.status, 200);
  assert.match(login.headers.get("set-cookie"), /^__Host-isletmem=.*HttpOnly; SameSite=Strict; Path=\/; Secure$/);
  const desktop = login.headers.get("set-cookie").split(";")[0];
  const phoneLogin = await post("login", { code: env.APP_PASSWORD });
  const phone = phoneLogin.headers.get("set-cookie").split(";")[0];
  instance.store.add("accounts", { name: "Ortak kasa", type: "cash" });
  instance.store.add("contacts", { name: "Ortak müşteri", type: "customer", openingAmount: "1000", openingSide: "receivable" });
  const c = instance.store.data.contacts[0];
  const saved = await post("add", { kind: "transactions", input: { type: "income", contactId: c.id, accountId: instance.store.data.accounts[0].id, amount: "300,01", description: "Uzaktan tahsilat", date: "2026-10-17" } }, phone);
  assert.equal((await saved.json()).ok, true);
  const read = await (await fetch(base + "/api/read", { headers: { cookie: desktop } })).json();
  assert.equal(D.balance(read.data, c.id), 69999);
  await instance.shutdown();
  instance = await start(env);
  base = `http://127.0.0.1:${instance.service.server.address().port}`;
  assert.equal(D.balance(instance.store.data, c.id), 69999);
  assert.equal((await fetch(base + "/api/read", { headers: { cookie: phone } })).status, 401);
  assert.equal(fs.readdirSync(path.join(env.DATA_DIR, "backups")).length, 1);
});
test("Masaüstü yedeği toplamları değiştirmeden boş sisteme aktarılır; hatalı veya dolu sistem korunur", t => {
  const { dir } = fixture(t);
  const source = new Store(path.join(dir, "desktop.json"));
  source.add("accounts", { name: "Kasa", type: "cash" });
  source.add("contacts", { name: "Mevcut cari", type: "customer", openingAmount: "150,29", openingSide: "receivable" });
  const c = source.data.contacts[0];
  source.add("transactions", { type: "income", contactId: c.id, accountId: source.data.accounts[0].id, amount: "50,01", description: "Eski tahsilat", date: "2026-10-17" });
  const destination = new Store(path.join(dir, "cloud.json"));
  const bad = structuredClone(source.data); bad.transactions[0].accountId = "orphan";
  assert.throws(() => importBackup(destination, bad), /bağlantı/);
  assert.equal(destination.data.contacts.length, 0);
  importBackup(destination, source.data);
  assert.deepEqual(destination.data, source.data);
  assert.equal(D.balance(destination.data, c.id), 10028);
  assert.throws(() => importBackup(destination, source.data), /boş sisteme/);
  assert.equal(D.balance(new Store(destination.file).data, c.id), 10028);
});
